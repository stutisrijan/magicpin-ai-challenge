_SUPPORT_ORDER = ("agg", "offer", "review", "customer", "signal", "derived", "seasonal", "trend", "merchant", "perf")
_SUPPORT_CAPS = {"agg": 4, "offer": 3, "review": 2, "customer": 5, "signal": 3, "perf": 4, "merchant": 2}


def _prompt_support(facts: FactSheet, limit: int = 14) -> list:
    """Most useful support facts first (cohorts, offers, reviews) instead of a wall of perf numbers."""
    groups: dict[str, list] = {}
    for f in facts.support_facts:
        groups.setdefault(f.key.split(".")[0], []).append(f)
    out: list = []
    for g in _SUPPORT_ORDER:
        out.extend(groups.get(g, [])[: _SUPPORT_CAPS.get(g, 2)])
    return out[:limit]


def fallback_reply(req: dict) -> dict:
    """Last-resort reply when the engine itself fails: exit on a stop, act on a clear yes, else back off."""
    message = req.get("message") if isinstance(req, dict) else ""
    message = message if isinstance(message, str) else ""
    intent = classify_inbound(message, None, None)
    if intent.label in ("opt_out", "hostile", "decline", "auto_reply", "thanks_close"):
        return {"action": "end", "rationale": f"Closing politely ({intent.label.replace('_', ' ')} detected)."}
    if intent.label == "wait_request":
        return {"action": "wait", "wait_seconds": int(intent.details.get("wait_seconds") or DEFAULT_WAIT_S),
                "rationale": "Merchant asked for time; backing off."}
    if intent.label == "accept":
        return {"action": "send", "cta": CTA_BINARY_CONFIRM,
                "body": "Great, on it. I'm preparing the draft now and will share it here next. "
                        "Reply CONFIRM to proceed.",
                "rationale": "Merchant committed; moving straight to action with a single confirm."}
    return {"action": "wait", "wait_seconds": DEFAULT_WAIT_S,
            "rationale": "Could not compose a grounded reply; backing off 30 minutes rather than sending a generic "
                         "message."}


