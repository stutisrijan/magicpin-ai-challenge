# --------------------------------------------------------------------------- normalisation


def normalize_text(text: Any) -> str:
    """Lower-case, drop apostrophes inside words ("let's" -> "lets"), strip punctuation and
    emoji, collapse spaces. Devanagari letters and vowel signs are kept."""
    if not isinstance(text, str) or not text:
        return ""
    s = unicodedata.normalize("NFKC", text).lower()
    s = re.sub(r"(?<=\w)['’`´](?=\w)", "", s)
    out = []
    for ch in s:
        cat = unicodedata.category(ch)
        out.append(ch if cat[0] in "LNM" else " ")
    return re.sub(r"\s+", " ", "".join(out)).strip()


_DV = "ऀ-ॿ"


def _dv(phrase: str) -> str:
    """Devanagari phrase with script-aware boundaries (\\b is unreliable around vowel signs)."""
    return rf"(?<![{_DV}]){phrase}(?![{_DV}])"


def _rx(*parts: str) -> re.Pattern:
    return re.compile("|".join(f"(?:{p})" for p in parts))


