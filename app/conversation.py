@dataclass
class Intent:
    label: str                         # auto_reply | opt_out | hostile | thanks_close | slot_choice | wait_request
                                       # edit | decline | accept | off_topic | question | engaged | other
    confidence: float = 0.5
    details: dict[str, Any] = field(default_factory=dict)


def parse_wait_seconds(text: str) -> int:
    """How long the merchant asked us to wait, in seconds (default 30 minutes)."""
    norm = normalize_text(text)
    secs: float | None = None
    m = _DURATION_RE.search(norm)
    if re.search(r"\b(?:half an hour|aadha ghanta|adha ghanta)\b", norm):
        secs = 1800
    elif m:
        qty_raw, unit = m.group(1), m.group(2)
        qty = _NUM_WORDS.get(qty_raw)
        if qty is None:
            try:
                qty = float(qty_raw)
            except ValueError:
                qty = 1
        secs = qty * _UNIT_S.get(unit, 3600)
    elif re.search(r"\b(?:day after tomorrow|parso)\b", norm):
        secs = 2 * 86400
    elif re.search(r"\b(?:next month|agle mahine|agle month)\b", norm):
        secs = 30 * 86400
    elif re.search(r"\b(?:next week|agle hafte|agle week|next (?:monday|tuesday|wednesday|thursday|friday|saturday"
                   r"|sunday))\b", norm) or "अगले हफ्ते" in norm:
        secs = 7 * 86400
    elif re.search(r"\bweekend\b", norm):
        secs = 2 * 86400
    elif re.search(r"\b(?:tomorrow|tmrw?|kal|not today|aaj nahi)\b", norm) or re.search(_dv("कल"), norm):
        secs = 86400
    elif re.search(r"\b(?:tonight|this evening|evening|shaam|raat)\b", norm):
        secs = 4 * 3600
    elif re.search(r"\b(?:afternoon|dopahar)\b", norm):
        secs = 3 * 3600
    if secs is None:
        secs = DEFAULT_WAIT_S
    return int(max(MIN_WAIT_S, min(MAX_WAIT_S, secs)))


def _split_sentences(raw: str) -> list[tuple[str, bool]]:
    """[(normalised sentence, ended_with_question_mark)]."""
    out: list[tuple[str, bool]] = []
    for m in re.finditer(r"[^.!?\n।]+[.!?\n।]*", raw or ""):
        chunk = m.group(0)
        norm = normalize_text(chunk)
        if norm:
            out.append((norm, "?" in chunk))
    return out


def _genuine_question(raw: str) -> str:
    """The first real question in the message (not "what's next?" style commitments), normalised."""
    for sent, qmark in _split_sentences(raw):
        is_q = qmark or bool(_Q_START_RE.search(sent)) or bool(_Q_ANY_RE.search(sent))
        if is_q and not _ACCEPT_Q_RE.search(sent):
            return sent
    return ""


def question_type(text: str) -> str:
    norm = normalize_text(text)
    low = (text or "").lower()
    for qtype, rx in _QTYPES:
        if rx.search(norm) or (qtype == "price" and "₹" in low):
            return qtype
    return "details"


def _off_topic(norm: str, kind: str = "") -> tuple[str, str] | None:
    for area, thing, rx in _OFF_TOPIC:
        if not rx.search(norm):
            continue
        if thing in ("GST", "GST filing") and _GST_PRICE_RE.search(norm) and not _GST_FILING_RE.search(norm):
            continue                           # "is it inclusive of GST?" is a pricing question
        if area == "lawyer" and kind in ("regulation_change", "supply_alert"):
            continue                           # legal questions about a compliance item are on-topic
        return area, thing
    return None


def _slot_choice(raw: str, norm: str, slots: list[str]) -> int | None:
    if not slots:
        return None
    m = re.fullmatch(r"(?:option |slot |number |no |choice )?([1-9])(?: (?:please|pls|plz|works|chalega|theek hai|ok"
                     r"|okay|done|confirm|wala|vala|is fine|fine|good))*", norm)
    if m:
        idx = int(m.group(1)) - 1
        return idx if idx < len(slots) else None
    words = norm.split()
    for w in words:
        if w in _ORDINALS and _ORDINALS[w] < len(slots) and len(words) <= 8:
            return _ORDINALS[w]
    labels = [s.lower() for s in slots]
    hits: set[int] = set()
    for key, names in _DAYS.items():
        if any(n in words for n in names):
            hits |= {i for i, lab in enumerate(labels) if re.match(rf"\W*{key}", lab) or re.search(rf"\b{key}\w*", lab)}
    for clock in re.findall(r"\b(\d{1,2})(?::(\d{2}))? ?(am|pm)\b", (raw or "").lower()):
        hour, minute, ampm = clock
        pat = rf"\b{int(hour)}(?::{minute or '00'})? ?{ampm}\b" if minute else rf"\b{int(hour)}(?::00)? ?{ampm}\b"
        hits |= {i for i, lab in enumerate(labels) if re.search(pat, lab)}
    if len(hits) == 1:
        return hits.pop()
    return None


def classify_inbound(text: str, conv: Conversation | None, merchant_state: MerchantState | None) -> Intent:
    """Deterministic intent for one inbound message. Ordered rules; the first match wins."""
    raw = text if isinstance(text, str) else ("" if text is None else str(text))
    norm = normalize_text(raw)
    stage = conv.stage if conv is not None else "opened"
    kind = conv.kind if conv is not None else ""
    slots = list((conv.meta.get("slots") if conv is not None else None) or [])
    emoji_pos = any(ch in raw for ch in _POSITIVE_EMOJI)
    if not norm:
        if emoji_pos:
            return Intent("thanks_close" if stage in ("action", "done") else "accept", 0.6,
                          {"strength": "weak", "emoji": True})
        return Intent("other", 0.2, {"empty": True})

    opt_out = bool(_OPT_OUT_RE.search(norm)) or (bool(_STOP_RE.search(norm)) and not _STOP_OK_RE.search(norm))
    hostile = bool(_HOSTILE_RE.search(norm))
    accept_strong = bool(_ACCEPT_STRONG_RE.search(norm))
    accept_weak = bool(_ACCEPT_WEAK_RE.search(norm))
    question = _genuine_question(raw)
    has_q = bool(question)

    defer = bool(_WAIT_DEFER_RE.search(norm))
    time_ref = bool(_WAIT_TIME_RE.search(norm))
    not_decline = bool(_NOT_DECLINE_RE.search(norm))
    decline_strong = bool(_DECLINE_STRONG_RE.search(norm)) and not not_decline
    decline_weak = bool(_DECLINE_WEAK_RE.search(norm)) and not not_decline

    # 1. auto-reply: canned phrasing, or the same longer text repeated (in this thread / by this merchant)
    #    with no intent of its own (a merchant may legitimately repeat "abhi nahi, kal baat karte hain")
    strong = _AUTO_STRONG_RE.findall(norm)
    weak = _AUTO_WEAK_RE.findall(norm)
    other_signal = opt_out or hostile or accept_strong or has_q
    any_intent = (opt_out or hostile or accept_strong or accept_weak or has_q or defer or time_ref or decline_strong
                  or decline_weak or bool(_STOP_RE.search(norm)))
    repeated = not any_intent and _is_repeat_text(norm, raw, conv, merchant_state)
    if strong or len(weak) >= 2 or (weak and not other_signal) or repeated:
        why = "canned phrasing" if (strong or weak) else "same text repeated"
        return Intent("auto_reply", 0.95 if strong or repeated else 0.75, {"why": why, "norm": norm})

    # 2. explicit opt-out beats hostility; 3. hostility without a stop
    if opt_out:
        return Intent("opt_out", 0.95, {"hostile": hostile})
    if hostile:
        return Intent("hostile", 0.85, {})

    # 4. thanks after the task is delivered closes the conversation
    thanks_only = bool(_THANKS_ONLY_RE.match(norm)) and (bool(_GRATITUDE_RE.search(norm)) or emoji_pos)
    thanks_only = thanks_only or (bool(_THANKS_DV_RE.search(norm)) and len(norm.split()) <= 4)
    if thanks_only and "confirm" not in norm and stage in ("action", "done"):
        return Intent("thanks_close", 0.9, {})
    if stage == "done" and not has_q and (thanks_only or (accept_weak and len(norm.split()) <= 3)):
        return Intent("thanks_close", 0.7, {"ack": True})
    # plain "ok thanks" is an acknowledgement, not a commitment; a second one after our follow-up closes
    thanks_ack = thanks_only and (bool(_THANKS_WORD_RE.search(norm)) or bool(_THANKS_DV_RE.search(norm)))
    if thanks_ack and stage == "engaged":
        return Intent("thanks_close", 0.7, {"ack": True})
    if thanks_ack:
        return Intent("engaged", 0.6, {"ack": True})

    # 5. customer picks an offered slot
    slot_idx = _slot_choice(raw, norm, slots)
    if slot_idx is not None and not has_q:
        return Intent("slot_choice", 0.9, {"slot_index": slot_idx, "slot": slots[slot_idx]})

    # 6. wait request: deferral language, or a bare time reference without a commitment
    if defer or (time_ref and not accept_strong and not has_q):
        return Intent("wait_request", 0.85, {"wait_seconds": parse_wait_seconds(raw), "deferral": defer})

    # 7. feedback on a delivered draft
    if stage == "action" and _EDIT_RE.search(norm):
        return Intent("edit", 0.75, {})

    # 8. decline (no question attached)
    if not has_q and (decline_strong or decline_weak) and not accept_strong:
        return Intent("decline", 0.85 if decline_strong else 0.7, {})

    off = _off_topic(norm, kind)
    positive = accept_strong or accept_weak or emoji_pos
    # 9. commitment (a real question attached turns it into "answer, then proceed")
    if positive and not off:
        if has_q:
            return Intent("question", 0.8, {"qtype": question_type(question), "positive": True, "question": question})
        return Intent("accept", 0.9 if accept_strong else 0.75,
                      {"strength": "strong" if accept_strong else "weak", "stage": stage})
    # 10. off-topic ask; 11. question
    if off:
        return Intent("off_topic", 0.85, {"area": off[0], "thing": off[1], "positive": positive})
    if has_q:
        return Intent("question", 0.75, {"qtype": question_type(question), "question": question})
    topics = rt.extract_topics(raw)
    if topics:
        return Intent("accept", 0.7, {"strength": "implicit", "topics": topics})
    return Intent("engaged", 0.5, {"words": len(norm.split())})


def _is_repeat_text(norm: str, raw: str, conv: Conversation | None, mstate: MerchantState | None) -> bool:
    """Same longer text already received in this conversation, or 2+ times from this merchant overall."""
    if len(norm) < 20 or len(norm.split()) < 4:
        return False
    if conv is not None:
        prior = [t for t in conv.turns if t.role != "bot"]
        if prior and prior[-1].body == raw:
            prior = prior[:-1]                 # the engine appends the inbound turn before classifying
        if any(normalize_text(t.body) == norm for t in prior):
            return True
    if mstate is not None and mstate.auto_reply_texts.get(norm, 0) >= 1:
        return True
    return False


# --------------------------------------------------------------------------- lazy modules


def _module(name: str) -> Any:
    try:
        return importlib.import_module(name)
    except Exception:  # a missing / broken sibling must never break replies
        log.warning("module %s unavailable", name)
        return None


def _s(value: Any) -> str:
    return value.strip() if isinstance(value, str) else ("" if value is None else str(value).strip())


def _snippet(text: str, limit: int = 60) -> str:
    t = re.sub(r"\s+", " ", text or "").strip()
    return t if len(t) <= limit else t[: limit - 1].rstrip() + "…"


def _human_duration(secs: int) -> str:
    if secs % 604800 == 0:
        n = secs // 604800
        return f"{n} week{'s' if n > 1 else ''}"
    if secs % 86400 == 0:
        n = secs // 86400
        return "24 hours" if n == 1 else f"{n} days"
    if secs >= 3600 and secs % 3600 == 0:
        n = secs // 3600
        return f"{n} hour{'s' if n > 1 else ''}"
    return f"{max(1, secs // 60)} minutes"


def _norm_body(text: str) -> str:
    s = str(text or "").lower().replace("’", "'")
    s = re.sub(r"[^\w₹%]+", " ", s)
    return re.sub(r"\s+", " ", s).strip()


_ASK_RE = re.compile(
    r"(?:want me to(?: go ahead and)?|shall i|should i|reply yes and i(?:'|’)?ll|say yes and i(?:'|’)?ll"
    r"|just say (?:yes|go) and i(?:'|’)?ll)\s+([^?.!\n]{6,160})", re.IGNORECASE)


def extract_ask(body: str) -> str:
    """The offer made in an English opener ("Want me to draft 3 posts?" -> "draft 3 posts")."""
    matches = _ASK_RE.findall(body or "")
    if not matches:
        return ""
    ask = re.sub(r"\s+", " ", matches[-1]).strip(" ,;:-—")
    return ask if len(ask.split()) >= 2 else ""


# --------------------------------------------------------------------------- engine


@dataclass
class Decision:
    action: str                          # send | wait | end
    move: str                            # nudge, apology, action, confirm, answer, answer_action, slot, ...
    rationale: str = ""
    wait_seconds: int = 0
    end_reason: str = ""
    soft: bool = False


class ConversationEngine:
    """Rule-first multi-turn handler. One instance per process (state lives in the stores)."""

    def __init__(self, contexts: ContextStore, convs: ConversationStore, llm: Any = None) -> None:
        self.contexts = contexts
        self.convs = convs
        self.llm = llm

    # ------------------------------------------------------------------ opener registration

    def open_from_action(self, action: dict, composition: dict, now: str | None = None) -> None:
        """Store a tick opener as a conversation (idempotent) and append the opener bot turn."""
        action = action if isinstance(action, dict) else {}
        composition = composition if isinstance(composition, dict) else {}
        cid = _s(action.get("conversation_id"))
        if not cid:
            return
        meta = composition.get("meta") if isinstance(composition.get("meta"), dict) else {}
        body = _s(action.get("body") or composition.get("body"))
        trigger_id = _s(action.get("trigger_id") or meta.get("trigger_id")) or None
        kind = _s(meta.get("kind"))
        if not kind and trigger_id:
            trig = self.contexts.get("trigger", trigger_id)
            kind = _s((trig or {}).get("kind")) if isinstance(trig, dict) else ""
        self.convs.observe_time(now)
        fields = {
            "merchant_id": _s(action.get("merchant_id") or meta.get("merchant_id")) or None,
            "customer_id": _s(action.get("customer_id") or meta.get("customer_id")) or None,
            "trigger_id": trigger_id,
            "kind": kind,
            "send_as": _s(action.get("send_as") or composition.get("send_as")) or SEND_AS_VERA,
            "offer": _s(meta.get("offer")),
            "suppression_key": _s(action.get("suppression_key") or composition.get("suppression_key")),
            "language": _s(meta.get("language")),
            "facts_digest": [str(f) for f in (meta.get("facts") or []) if f][:8],
        }
        conv = self.convs.get(cid)
        if conv is None:
            conv = self.convs.create(cid, **fields)
        else:
            for key, value in fields.items():
                if value:
                    setattr(conv, key, value)
        conv.meta.update({
            "opener_cta": _s(action.get("cta") or composition.get("cta")),
            "template_name": _s(action.get("template_name") or composition.get("template_name")),
            "ask": extract_ask(body),
            "source": _s(meta.get("source")),
            "created_by": "tick",
        })
        if body and not any(t.role == "bot" for t in conv.turns):
            self.convs.add_turn(cid, "bot", body, ts=now, seq=next(_SEQ), move="opener",
                                cta=_s(action.get("cta") or composition.get("cta")))
        if not conv.inbound():
            conv.stage = "opened"
            conv.status = "active"

    # ------------------------------------------------------------------ reply

    async def handle_reply(self, req: dict) -> dict:
        """Next move for one inbound message. Never raises (except cancellation)."""
        started = time.monotonic()
        try:
            return await self._handle(req if isinstance(req, dict) else {}, started)
        except asyncio.CancelledError:
            raise
        except Exception:
            log.exception("handle_reply failed; using a safe fallback")
            return fallback_reply(req if isinstance(req, dict) else {})

    async def _handle(self, req: dict, started: float) -> dict:
        deadline = started + float(config.settings.reply_deadline_s)
        cid = _s(req.get("conversation_id")) or "conv_unknown"
        message = req.get("message")
        message = message if isinstance(message, str) else ("" if message is None else str(message))
        received = req.get("received_at") if isinstance(req.get("received_at"), str) else None
        self.convs.observe_time(received)
        now_iso = received if parse_iso(received) else (self.convs.sim_now or utc_now_iso())
        from_role = (_s(req.get("from_role")) or "merchant").lower()

        conv = self._get_or_create(cid, req, from_role, now_iso)
        role = "customer" if from_role == "customer" else "merchant"
        customer_facing = role == "customer" or bool(conv.customer_id) or conv.send_as == SEND_AS_MERCHANT
        mid = conv.merchant_id
        mstate = self.convs.merchant(mid) if mid else MerchantState(merchant_id="")

        self.convs.add_turn(cid, role, message, ts=now_iso, seq=next(_SEQ))
        inbound = conv.turns[-1] if conv.turns else None
        facts = self._facts(conv, customer_facing, now_iso)       # includes the inbound turn's numbers
        conv.meta["slots"] = list(facts.slots)

        intent = classify_inbound(message, conv, mstate)
        if inbound is not None:
            inbound.meta["intent"] = intent.label
        norm = normalize_text(message)
        if role == "merchant" and not customer_facing and len(norm.split()) >= 4:
            mstate.auto_reply_texts[norm] = mstate.auto_reply_texts.get(norm, 0) + 1

        decision = self._decide(conv, mstate, intent, message, customer_facing, req, now_iso)
        if decision.action == "wait":
            secs = int(decision.wait_seconds or DEFAULT_WAIT_S)
            conv.status = "waiting"
            base = parse_iso(now_iso)
            conv.wait_until = (base + timedelta(seconds=secs)).isoformat().replace("+00:00", "Z") if base else None
            return {"action": "wait", "wait_seconds": secs, "rationale": decision.rationale}
        if decision.action == "end":
            conv.status = "ended"
            conv.ended_reason = decision.end_reason or intent.label
            return {"action": "end", "rationale": decision.rationale}

        plan = self._language(conv, facts, message, customer_facing)
        body, cta, label, source = await self._write(conv, facts, intent, decision, message, customer_facing,
                                                     plan, mstate, deadline)
        self._after_send(conv, mstate, decision, intent, body, cta, label, source, plan, now_iso)
        rationale = self._send_rationale(decision, intent, message, label, source)
        return {"action": "send", "body": body, "cta": cta, "rationale": rationale}

    # ------------------------------------------------------------------ conversation lookup

    def _get_or_create(self, cid: str, req: dict, from_role: str, now_iso: str) -> Conversation:
        mid = _s(req.get("merchant_id")) or None
        cust = _s(req.get("customer_id")) or None
        conv = self.convs.get(cid)
        if conv is not None:
            if not conv.merchant_id and mid:
                conv.merchant_id = mid
            if not conv.customer_id and cust:
                conv.customer_id = cust
            return conv
        fields: dict[str, Any] = {
            "merchant_id": mid, "customer_id": cust, "kind": "unknown",
            "send_as": SEND_AS_MERCHANT if (cust or from_role == "customer") else SEND_AS_VERA,
        }
        parent = self._recent_parent(mid, cust, now_iso)
        if parent is not None:
            fields.update(kind=parent.kind or "unknown", offer=parent.offer, trigger_id=parent.trigger_id,
                          facts_digest=list(parent.facts_digest), language=parent.language,
                          customer_id=parent.customer_id)
        conv = self.convs.create(cid, **fields)
        conv.meta["created_by"] = "reply"
        if parent is not None:
            conv.meta["inherited_from"] = parent.conversation_id
            conv.meta["ask"] = parent.meta.get("ask", "")
        return conv

    def _recent_parent(self, mid: str | None, cust: str | None, now_iso: str) -> Conversation | None:
        """The merchant's latest tick-opened conversation (same audience), to give an unknown id context."""
        if not mid:
            return None
        now_dt = parse_iso(now_iso)
        best: Conversation | None = None
        for c in self.convs.for_merchant(mid):
            if c.meta.get("created_by") != "tick" or (c.customer_id or None) != (cust or None):
                continue
            ts = parse_iso(c.updated_at)
            if now_dt and ts and abs((now_dt - ts).total_seconds()) > 3 * 86400:
                continue
            if best is None or (c.updated_at or "") >= (best.updated_at or ""):
                best = c
        return best

    # ------------------------------------------------------------------ facts / language

    def _facts(self, conv: Conversation, customer_facing: bool, now_iso: str) -> FactSheet:
        merchant = self.contexts.get("merchant", conv.merchant_id) if conv.merchant_id else None
        turns = [{"from": "vera" if t.role == "bot" else t.role, "body": t.body, "ts": t.ts} for t in conv.turns]
        facts_mod = _module("app.facts")
        if not isinstance(merchant, dict) or facts_mod is None:
            sheet = FactSheet(kind=conv.kind or "", merchant_id=conv.merchant_id or "",
                              customer_id=conv.customer_id, scope="customer" if customer_facing else "merchant",
                              send_as=SEND_AS_MERCHANT if customer_facing else SEND_AS_VERA)
            sheet.allowed_numbers = _numbers_in(t["body"] for t in turns)
            return sheet
        trigger = self.contexts.get("trigger", conv.trigger_id) if conv.trigger_id else None
        if not isinstance(trigger, dict):
            known = conv.kind if conv.kind and conv.kind != "unknown" else ""
            trigger = {"id": "", "kind": known, "merchant_id": conv.merchant_id, "payload": {}} if known else {}
        customer = self.contexts.get("customer", conv.customer_id) if conv.customer_id else None
        category = self.contexts.category_for(merchant, trigger)
        try:
            sheet = facts_mod.build_facts(category, merchant, trigger, customer, now=now_iso, conversation_turns=turns)
        except Exception:
            log.exception("build_facts failed in reply")
            sheet = FactSheet(kind=conv.kind or "", merchant_id=conv.merchant_id or "")
        if customer_facing and sheet.scope != "customer":
            # customer context missing: never address the customer by the owner's name
            sheet.salutation = ""
            sheet.signer = sheet.signer or sheet.merchant_name
        return sheet

    def _language(self, conv: Conversation, facts: FactSheet, message: str, customer_facing: bool) -> LanguagePlan:
        lang_mod = _module("app.language")
        base = facts.language if isinstance(facts.language, LanguagePlan) else LanguagePlan()
        if conv.language and lang_mod is not None and conv.language != base.code:
            try:
                base = lang_mod.plan_for_code(conv.language)
            except Exception:
                pass
        if lang_mod is None:
            return base
        try:
            return lang_mod.plan_for_reply(base, message)
        except Exception:
            return base

    # ------------------------------------------------------------------ move selection

    def _decide(self, conv: Conversation, mstate: MerchantState, intent: Intent, message: str,
                customer_facing: bool, req: dict, now_iso: str) -> Decision:
        label = intent.label
        snip = _snippet(message)
        soft = False

        if label == "auto_reply":
            return self._auto_reply_move(conv, mstate, intent, message, customer_facing, now_iso)
        conv.auto_reply_streak = 0

        if conv.status == "ended":
            reopen = self._reopen_mode(conv, mstate, intent, customer_facing)
            if reopen is None:
                return Decision("end", "end", f"Conversation already closed ({conv.ended_reason or 'ended'}); "
                                              f"'{snip}' does not call for re-engaging, so staying quiet.",
                                end_reason=conv.ended_reason or "ended")
            conv.status = "active"
            conv.meta["reopened"] = int(conv.meta.get("reopened", 0)) + 1
            soft = reopen == "soft"
        elif conv.status == "waiting":
            conv.status = "active"

        if label == "opt_out":
            if customer_facing:
                conv.meta["customer_opted_out"] = True
                why = "Customer asked us to stop"
            else:
                mstate.opted_out = True
                mstate.opted_out_at = now_iso
                why = "Merchant explicitly opted out"
            return Decision("end", "end", f"{why} ('{snip}'). Closing the conversation and suppressing further "
                                          f"proactive messages.", end_reason="opt_out")

        if label == "hostile":
            conv.hostile_count += 1
            if not customer_facing:
                mstate.hostile_count += 1
            repeated = conv.hostile_count >= 2 or conv.meta.get("apologized")
            if repeated or (not customer_facing and mstate.hostile_count >= 3):
                return Decision("end", "end", f"Repeated frustration ('{snip}'); exiting gracefully without further "
                                              f"engagement.", end_reason="hostile")
            return Decision("send", "apology")

        if label == "thanks_close":
            return Decision("end", "end", f"Task delivered and acknowledged ('{snip}'); closing the conversation "
                                          f"without another ask.", end_reason="done")

        if label == "wait_request":
            secs = int(intent.details.get("wait_seconds") or DEFAULT_WAIT_S)
            return Decision("wait", "wait", f"Merchant asked for time ('{snip}'); backing off "
                                            f"{_human_duration(secs)} before following up.", wait_seconds=secs)

        if label == "decline":
            return Decision("end", "end", f"Declined ('{snip}'); closing politely without pushing the offer.",
                            end_reason="decline")

        if label == "slot_choice":
            return Decision("send", "slot", soft=soft)

        if soft:
            # re-opened after an opt-out / hostility: answer briefly, never pitch
            if label == "off_topic":
                return Decision("send", "off_topic", soft=True)
            if label == "question":
                return Decision("send", "answer", soft=True)

        if label == "edit":
            return Decision("send", "edit" if conv.stage == "action" else "action")

        if label == "accept":
            if customer_facing:
                held = str(conv.meta.get("artifact") or "")
                if conv.stage == "action" and held.startswith("held "):
                    # "CONFIRM" after we held a slot: book exactly that slot.
                    intent.details["slot"] = held[len("held "):]
                    return Decision("send", "slot")
                return Decision("send", "customer_accept")
            if conv.stage == "action":
                return Decision("send", "confirm")
            if conv.stage == "done":
                return Decision("end", "end", f"Task already completed; '{snip}' needs no further message.",
                                end_reason="done")
            return Decision("send", "action")

        if label == "question":
            if intent.details.get("positive") and not customer_facing and conv.stage not in ("action", "done"):
                return Decision("send", "answer_action")
            return Decision("send", "answer")

        if self._too_long(conv, req):
            return Decision("end", "end", "Conversation has run long without progress; closing gracefully instead "
                                          "of sending another nudge.", end_reason="max_turns")

        if label == "off_topic":
            conv.off_topic_count += 1
            return Decision("send", "off_topic", soft=conv.hostile_count > 0)

        # engaged / other
        if customer_facing and conv.stage == "done":
            return Decision("end", "end", f"Booking already confirmed; '{snip}' needs no further message.",
                            end_reason="done")
        if not customer_facing and conv.kind in ASK_KINDS and conv.stage in ("opened", "engaged") \
                and not intent.details.get("ack") and intent.details.get("words", 0) >= 1:
            return Decision("send", "action")      # they answered the question the opener asked
        return Decision("send", "continue")

    def _auto_reply_move(self, conv: Conversation, mstate: MerchantState, intent: Intent, message: str,
                         customer_facing: bool, now_iso: str) -> Decision:
        norm = normalize_text(message)
        conv_streak = self._streak([conv], norm)
        pool = [conv]
        if conv.merchant_id and not customer_facing:
            pool = [c for c in self.convs.for_merchant(conv.merchant_id) if not c.customer_id or c is conv]
        streak = max(conv_streak, self._streak(pool, norm))
        conv.auto_reply_streak = streak
        conv.auto_reply_total += 1
        snip = _snippet(message, 50)
        if customer_facing:
            if streak <= 1:
                return Decision("wait", "wait", f"Looks like an automated reply ('{snip}'); waiting a day for the "
                                                f"customer instead of replying to a bot.",
                                wait_seconds=AUTO_REPLY_WAIT_S)
            return Decision("end", "end", "Automated replies again; closing without further messages.",
                            end_reason="auto_reply")
        if streak <= 1 and conv.status != "ended":
            return Decision("send", "nudge")
        if streak == 2 and conv.status != "ended":
            return Decision("wait", "wait", f"Same auto-reply again (streak {streak}: '{snip}'); the owner is not at "
                                            f"the phone, so waiting 24 hours instead of burning turns.",
                            wait_seconds=AUTO_REPLY_WAIT_S)
        cooldown_min = int(config.settings.auto_reply_cooldown_min)
        base = parse_iso(now_iso)
        if mstate.merchant_id and base is not None:
            mstate.cooldown_until = (base + timedelta(minutes=cooldown_min)).isoformat().replace("+00:00", "Z")
        return Decision("end", "end", f"Auto-reply {max(streak, 3)} times in a row with no human response; closing "
                                      f"the conversation and pausing proactive sends to this merchant for "
                                      f"{cooldown_min} minutes.", end_reason="auto_reply")

    @staticmethod
    def _streak(pool: list[Conversation], norm: str) -> int:
        turns = [t for c in pool for t in c.turns if t.role != "bot" and "seq" in t.meta]
        turns.sort(key=lambda t: t.meta["seq"])
        streak = 0
        for t in reversed(turns):
            same = len(norm) >= 12 and normalize_text(t.body) == norm
            if t.meta.get("intent") == "auto_reply" or same:
                streak += 1
            else:
                break
        return max(1, streak)

    @staticmethod
    def _reopen_mode(conv: Conversation, mstate: MerchantState, intent: Intent, customer_facing: bool) -> str | None:
        """None: stay closed; "soft": answer briefly without pitching; "full": resume normally."""
        label = intent.label
        if label in ("opt_out", "hostile", "decline", "thanks_close", "wait_request", "auto_reply"):
            return None
        opted = conv.ended_reason in ("opt_out", "hostile") or conv.meta.get("customer_opted_out") or (
            mstate.opted_out and not customer_facing)
        if opted:
            if label in ("question", "off_topic"):
                return "soft"
            if label == "accept" and intent.details.get("strength") == "strong":
                if not customer_facing:
                    mstate.opted_out = False        # they explicitly asked us to go ahead again
                conv.meta.pop("customer_opted_out", None)
                return "full"
            return None
        if label in ("engaged", "other") and conv.ended_reason in ("done", "max_turns"):
            return None
        return "full"

    @staticmethod
    def _too_long(conv: Conversation, req: dict) -> bool:
        try:
            turn_no = int(req.get("turn_number") or 0)
        except (TypeError, ValueError):
            turn_no = 0
        inbound = len(conv.inbound())
        if max(inbound, turn_no // 2) > MAX_INBOUND_TURNS:
            return True
        progress_at = int(conv.meta.get("progress_bot_count", 0))
        return len(conv.bot_bodies()) - progress_at >= MAX_BOT_TURNS_WITHOUT_PROGRESS

    # ------------------------------------------------------------------ body

    def _reply_ctx(self, conv: Conversation, facts: FactSheet, intent: Intent, message: str,
                   customer_facing: bool, plan: LanguagePlan, soft: bool) -> rt.ReplyContext:
        lang = "hinglish" if plan.code in ("hinglish", "hi") else "en"
        kind = conv.kind if conv.kind and conv.kind != "unknown" else ""
        offer = self._offer(conv, facts, lang)
        topics = list(intent.details.get("topics") or rt.extract_topics(message))
        if not topics and kind in ASK_KINDS and intent.label == "engaged":
            topics = rt.extract_topics(message, loose=True)
        if not topics and not kind:
            last = next((h.get("body", "") for h in reversed(facts.history or [])
                         if h.get("from") == "merchant" and h.get("body") != message), "")
            topics = rt.extract_topics(last)
        return rt.ReplyContext(
            facts=facts, kind=kind, lang=lang, customer_facing=customer_facing, offer=offer, inbound=message,
            stage=conv.stage, variant=len(conv.bot_bodies()), topics=topics, soft=soft,
            artifact=str(conv.meta.get("artifact") or ""),
        )

    def _offer(self, conv: Conversation, facts: FactSheet, lang: str) -> str:
        """What the thread offered to do, as a verb phrase ("draft 3 Google posts")."""
        ask = str(conv.meta.get("ask") or "")
        if ask and lang == "en":
            return ask
        if conv.offer:
            return conv.offer
        # unknown thread: Vera's last offer in the merchant's history, else the most useful next step
        for h in reversed(facts.history or []):
            if h.get("from") == "vera":
                found = extract_ask(str(h.get("body") or ""))
                if found:
                    return found
                break
        view = rt.FactView(facts)
        if view.has("signal.stale_posts") or view.has("signal.no_recent_post"):
            return "draft a fresh Google post for you"
        if facts.offers_active:
            return f"draft a Google post for your {facts.offers_active[0]}"
        return ""

    async def _write(self, conv: Conversation, facts: FactSheet, intent: Intent, decision: Decision, message: str,
                     customer_facing: bool, plan: LanguagePlan, mstate: MerchantState,
                     deadline: float) -> tuple[str, str, str, str]:
        ctx = self._reply_ctx(conv, facts, intent, message, customer_facing, plan, decision.soft)
        prior = [b for b in conv.bot_bodies()] + list(mstate.sent_bodies)
        prior_norm = {_norm_body(b) for b in prior}
        reply = self._template(decision.move, ctx, intent)
        for _ in range(4):                      # anti-repetition: rotate wording before giving up
            if _norm_body(reply.body) not in prior_norm:
                break
            ctx.variant += 1
            reply = self._template(decision.move, ctx, intent)
        body, cta, label, source = reply.body, reply.cta, reply.label, "template"
        if _norm_body(body) in prior_norm:
            body = rt.distinct_variant(body, ctx, prior_norm)

        if decision.move in LLM_MOVES and not customer_facing and not decision.soft and self._llm_ready():
            cand = await self._llm_body(conv, facts, intent, decision, message, plan, body, cta, prior, deadline)
            if cand:
                body, source = cand, "llm"
        if cta not in CTA_VALUES:
            cta = CTA_OPEN_ENDED
        return body.strip(), cta, label, source

    def _template(self, move: str, ctx: rt.ReplyContext, intent: Intent) -> rt.Reply:
        d = intent.details
        if move == "nudge":
            return rt.auto_reply_nudge(ctx)
        if move == "apology":
            return rt.hostile_apology(ctx)
        if move == "off_topic":
            return rt.off_topic_redirect(ctx, str(d.get("area") or "personal"), str(d.get("thing") or "That"))
        if move == "answer":
            return rt.answer_question(ctx, str(d.get("qtype") or "details"))
        if move == "answer_action":
            return rt.answer_with_artifact(ctx, str(d.get("qtype") or "details"))
        if move == "action":
            return rt.action_artifact(ctx)
        if move == "confirm":
            return rt.confirm_done(ctx)
        if move == "edit":
            return rt.edit_ack(ctx)
        if move == "slot":
            slots = ctx.facts.slots
            idx = d.get("slot_index")
            slot = str(d.get("slot") or (slots[idx] if isinstance(idx, int) and idx < len(slots) else ""))
            return rt.slot_confirmation(ctx, slot) if slot else rt.slot_prompt(ctx)
        if move == "customer_accept":
            return rt.customer_accept(ctx)
        return rt.continue_thread(ctx)

    # ------------------------------------------------------------------ LLM path

    def _llm_ready(self) -> bool:
        llm = self.llm
        if llm is None or not callable(getattr(llm, "complete_json", None)):
            return False
        try:
            available = getattr(llm, "available", None)
            return bool(available()) if callable(available) else True
        except Exception:
            return False

    async def _llm_body(self, conv: Conversation, facts: FactSheet, intent: Intent, decision: Decision,
                        message: str, plan: LanguagePlan, baseline: str, cta: str, prior: list[str],
                        deadline: float) -> str | None:
        remaining = deadline - time.monotonic() - REPLY_MARGIN_S
        if remaining < MIN_LLM_S:
            return None
        timeout = min(remaining, float(config.settings.llm_timeout_s))
        system, user = reply_prompt(conv, facts, intent, decision.move, baseline, cta, plan, message)
        try:
            res = await asyncio.wait_for(
                self.llm.complete_json(system, user, schema=REPLY_SCHEMA, timeout=timeout,
                                       max_tokens=LLM_MAX_TOKENS, temperature=0.0),
                timeout=timeout + 0.3)
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            log.info("reply LLM unavailable (%s)", type(exc).__name__)
            return None
        body = res.get("body") if isinstance(res, dict) else None
        if not isinstance(body, str) or not body.strip():
            return None
        body = body.strip()
        mode = "reply_action" if decision.move in ("action", "answer_action", "edit") else "reply"
        issues = check_body(body, facts, prior_bodies=prior, mode=mode, customer_facing=False)
        if issues:
            log.info("reply LLM output rejected: %s", issues[:3])
            return None
        return body

    # ------------------------------------------------------------------ bookkeeping

    def _after_send(self, conv: Conversation, mstate: MerchantState, decision: Decision, intent: Intent, body: str,
                    cta: str, label: str, source: str, plan: LanguagePlan, now_iso: str) -> None:
        move = decision.move
        self.convs.add_turn(conv.conversation_id, "bot", body, ts=now_iso, seq=next(_SEQ), move=move, cta=cta,
                            intent=intent.label, source=source, label=label)
        if mstate.merchant_id:
            mstate.sent_bodies.append(body)
        conv.language = plan.code
        progress = False
        if move in ("action", "answer_action") or (move == "customer_accept" and cta == CTA_BINARY_CONFIRM):
            conv.stage = "action"
            conv.meta["artifact"] = label
            progress = True
        elif move in ("confirm", "slot") or (move == "customer_accept" and cta == CTA_NONE):
            conv.stage = "done"
            progress = True
            if move == "slot":
                conv.meta["booked_slot"] = intent.details.get("slot", "")
        elif move == "apology":
            conv.meta["apologized"] = True
        elif conv.stage == "opened" and move not in ("nudge",):
            conv.stage = "engaged"
        if progress:
            conv.meta["progress_bot_count"] = len(conv.bot_bodies())

    @staticmethod
    def _send_rationale(decision: Decision, intent: Intent, message: str, label: str, source: str) -> str:
        snip = _snippet(message)
        label = rt.artifact_label(label) if label in rt._ART_LABELS else label
        d = intent.details
        move = decision.move
        via = " (LLM wording, validated)" if source == "llm" else ""
        if move == "nudge":
            return (f"Detected a WhatsApp Business auto-reply ('{_snippet(message, 50)}'); one short owner-directed "
                    f"nudge with a single YES ask instead of repeating the pitch.")
        if move == "apology":
            return (f"Merchant is frustrated ('{snip}'); one-line apology with an explicit STOP path and no pitch. "
                    f"Will close if it continues.")
        if move == "off_topic":
            tail = "answered briefly without pitching" if decision.soft else "redirected to the thread's offer"
            return f"Out-of-scope ask ({d.get('thing') or 'unrelated'}) politely declined; {tail}.{via}"
        if move == "answer":
            if decision.soft:
                return f"Re-opened only to answer a genuine question ('{snip}') from known facts; no pitch.{via}"
            return (f"Answered the {d.get('qtype', 'details')} question ('{snip}') only from known facts, saying so "
                    f"where unknown; one clear next step.{via}")
        if move == "answer_action":
            return (f"Positive reply with a question ('{snip}'): answered it from known facts and moved straight to "
                    f"action with the {label or 'draft'}; one CONFIRM step.{via}")
        if move == "action":
            return (f"Merchant committed ('{snip}'); switched from pitch to ACTION mode and delivered the "
                    f"{label or 'draft'} grounded in their own data, with one CONFIRM-style next step.{via}")
        if move == "confirm":
            return f"Merchant confirmed ('{snip}'); reporting what is done and what happens next, no further ask."
        if move == "edit":
            return f"Merchant asked for a change ('{snip}'); acknowledged it and kept a single CONFIRM step.{via}"
        if move == "slot":
            return f"Customer picked {d.get('slot') or 'a slot'}; confirming the exact slot with a reschedule path."
        if move == "customer_accept":
            return f"Customer said yes ('{snip}'); moving straight to the booking step with the exact options we have."
        return (f"Engaged reply without a clear yes/no ('{snip}'); acknowledged it and offered the next concrete step "
                f"with a single ask.{via}")


# --------------------------------------------------------------------------- validation + prompt


def _numbers_in(texts: Any) -> set[str]:
    out: set[str] = set()
    for text in texts:
        for tok in extract_number_tokens(str(text or "")):
            n = normalize_number(tok)
            if n is not None:
                out.add(n)
    return out


def check_body(body: str, facts: FactSheet, *, prior_bodies: list[str] = (), mode: str = "reply",
               customer_facing: bool = False) -> list[str]:
    """Validator issues for a reply body (app.validator when present, else basic local checks)."""
    validator = _module("app.validator")
    if validator is not None and callable(getattr(validator, "validate_body", None)):
        try:
            return list(validator.validate_body(body, facts, prior_bodies=list(prior_bodies), mode=mode,
                                                customer_facing=customer_facing))
        except Exception:
            log.exception("validator failed on reply body")
    return _basic_issues(body, facts, list(prior_bodies), mode, customer_facing)


def _basic_issues(body: str, facts: FactSheet, prior: list[str], mode: str, customer_facing: bool) -> list[str]:
    issues: list[str] = []
    low = body.lower()
    if re.search(r"https?://|www\.|\.com\b|\.in\b", low):
        issues.append("url")
    if mode == "reply_action":
        if rt.has_qualifying(body):
            issues.append("qualifying")
        if not any(w in low for w in ("done", "sending", "draft", "here", "confirm", "proceed", "next")):
            issues.append("no_action_word")
    if customer_facing and re.search(r"\b(?:vera|magic\s?pin)\b", low):
        issues.append("brand_mention")
    allowed = facts.allowed_numbers or set()
    for tok in extract_number_tokens(body):
        n = normalize_number(tok)
        marked = any(ch in tok for ch in "%₹") or tok.lower().endswith("x")
        if n and n not in allowed and (marked or not (n.isdigit() and int(n) <= 10)):
            issues.append(f"ungrounded_number: {tok}")
    if any(_norm_body(p) == _norm_body(body) for p in prior):
        issues.append("repeat")
    return issues


